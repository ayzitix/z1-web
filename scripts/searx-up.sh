#!/usr/bin/env bash
# Start the local SearXNG instance used by the z1 coding agent.
# Idempotent: safe to run repeatedly.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE_FILE="$ROOT/searxng/docker-compose.yml"
ENV_FILE="$ROOT/searxng/.env"
URL="http://127.0.0.1:8888"
CONTAINER="z1-searxng"

compose() { docker compose -f "$COMPOSE_FILE" "$@"; }

# --- 1. secret -------------------------------------------------------------
# Read the current value without sourcing the file (it may be malformed).
current_secret=""
if [[ -f "$ENV_FILE" ]]; then
  current_secret="$(grep -E '^SEARXNG_SECRET=' "$ENV_FILE" | head -n1 | cut -d= -f2- || true)"
  current_secret="${current_secret%\"}"; current_secret="${current_secret#\"}"
fi

if [[ -z "$current_secret" ]]; then
  if command -v openssl >/dev/null 2>&1; then
    secret="$(openssl rand -hex 32)"
  else
    secret="$(python3 -c 'import secrets; print(secrets.token_hex(32))')"
  fi

  if [[ -f "$ENV_FILE" ]] && grep -qE '^SEARXNG_SECRET=' "$ENV_FILE"; then
    # replace the (empty) value in place, keeping any other keys
    tmp="$(mktemp)"
    sed -E "s|^SEARXNG_SECRET=.*$|SEARXNG_SECRET=${secret}|" "$ENV_FILE" >"$tmp"
    mv "$tmp" "$ENV_FILE"
  else
    {
      echo "# generated by scripts/searx-up.sh — do not commit"
      echo "SEARXNG_SECRET=${secret}"
      grep -vE '^SEARXNG_SECRET=|^#' "$ENV_FILE" 2>/dev/null || true
    } >>"$ENV_FILE" 2>/dev/null || {
      printf '# generated by scripts/searx-up.sh — do not commit\nSEARXNG_SECRET=%s\n' "$secret" >"$ENV_FILE"
    }
  fi
  echo "[searx-up] generated a new SEARXNG_SECRET in searxng/.env"
fi

chmod 600 "$ENV_FILE"

# --- 2. bring it up --------------------------------------------------------
command -v docker >/dev/null 2>&1 || { echo "[searx-up] docker not found" >&2; exit 1; }
docker info >/dev/null 2>&1 || { echo "[searx-up] docker daemon not reachable" >&2; exit 1; }

echo "[searx-up] starting container..."
compose up -d --remove-orphans

# --- 3. wait for health (max 60s) -----------------------------------------
echo -n "[searx-up] waiting for healthy"
status=""
for _ in $(seq 1 60); do
  status="$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$CONTAINER" 2>/dev/null || echo missing)"
  case "$status" in
    healthy) break ;;
    exited|dead|missing) break ;;
  esac
  echo -n "."
  sleep 1
done
echo

if [[ "$status" != "healthy" ]]; then
  echo "[searx-up] container did not become healthy (status: $status)" >&2
  compose logs --tail=40 >&2 || true
  exit 1
fi

# --- 4. report -------------------------------------------------------------
echo
echo "  URL      : $URL"
echo "  Search   : $URL/search?q=typescript"
echo "  JSON     : curl -sS '$URL/search?q=typescript&format=json' | head -c 400"
echo "  Status   : $(docker inspect --format '{{.State.Status}} / health={{.State.Health.Status}}' "$CONTAINER")"
echo "  Image    : $(docker inspect --format '{{.Config.Image}}' "$CONTAINER")"
echo
compose ps
